"""Generates crates/ui/src/theme/palette.rs: Cartwave's own 70-colour palette.

usage: python make_palette.py > crates/ui/src/theme/palette_data.rs

A 5 x 14 grid: 14 hue columns (OKLCh hue, evenly spaced from red), 5 lightness rows
(light to dark). Every colour is ours: generated here from those parameters. Rules:
- the 12 colours in use before (the lane defaults and the Colour menu) stay, each in
  the grid cell nearest to it (OKLab), so existing projects look unchanged;
- no generated colour lies within OKLab dE < LIME_MIN of the toggle lime #C7D74E (the
  legacy pulse #C9D24A is the one exception: today's lane colour, kept);
- every colour leaves dark #111111 or light #F2F2F2 header text at >= 4.5:1 (the
  lightness is nudged until one of them passes);
- every colour stands apart from the lane rows (#171717 / #141414) by dE >= 0.25.
"""
import math

LIME = 0xC7D74E
LIME_MIN = 0.06
LEGACY = [0xC9D24A, 0x7F86E0, 0xB5AC98, 0xE39A42, 0xD9579A, 0x3CC4A6, 0x4FA8E0, 0xE0705A, 0xA77BE0, 0x7FD08A, 0xD8B83C, 0x8C98A8]
ROWS_L = [0.86, 0.78, 0.70, 0.62, 0.52]
COLS = 14
CHROMA = [0.10, 0.13, 0.15, 0.14, 0.12]


def srgb_to_lin(c):
    c /= 255.0
    return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4


def lin_to_srgb(c):
    c = max(0.0, min(1.0, c))
    return 255.0 * (12.92 * c if c <= 0.0031308 else 1.055 * c ** (1 / 2.4) - 0.055)


def hex_rgb(h):
    return ((h >> 16) & 255, (h >> 8) & 255, h & 255)


def oklab(h):
    r, g, b = (srgb_to_lin(v) for v in hex_rgb(h))
    l = 0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b
    m = 0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b
    s = 0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b
    l, m, s = (math.copysign(abs(v) ** (1 / 3), v) for v in (l, m, s))
    return (0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
            1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
            0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s)


def from_oklch(L, C, H):
    a, b = C * math.cos(math.radians(H)), C * math.sin(math.radians(H))
    l_ = L + 0.3963377774 * a + 0.2158037573 * b
    m_ = L - 0.1055613458 * a - 0.0638541728 * b
    s_ = L - 0.0894841775 * a - 1.2914855480 * b
    l, m, s = l_ ** 3, m_ ** 3, s_ ** 3
    r = 4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s
    g = -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s
    bb = -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s
    inside = all(-0.001 <= v <= 1.001 for v in (r, g, bb))
    rgb = tuple(int(round(lin_to_srgb(v))) for v in (r, g, bb))
    return (rgb[0] << 16) | (rgb[1] << 8) | rgb[2], inside


def gamut(L, C, H):
    """The colour at (L, C, H), chroma reduced until it fits sRGB."""
    while C > 0.0:
        h, ok = from_oklch(L, C, H)
        if ok:
            return h
        C -= 0.005
    return from_oklch(L, 0.0, H)[0]


def de(a, b):
    p, q = oklab(a), oklab(b)
    return math.sqrt(sum((x - y) ** 2 for x, y in zip(p, q)))


def lum(h):
    r, g, b = (srgb_to_lin(v) for v in hex_rgb(h))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def contrast(a, b):
    la, lb = sorted((lum(a), lum(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def lighten(h, t):
    r, g, b = hex_rgb(h)
    f = lambda v: int(round(v + (255 - v) * t))
    return (f(r) << 16) | (f(g) << 8) | f(b)


def text_ok(h):
    """One header ink reaches 4.5:1 on the colour as drawn: plain, and lit by
    hover and selection (the clip recipe lightens it by up to 10%)."""
    for c in (h, lighten(h, 0.10)):
        if max(contrast(c, 0x111111), contrast(c, 0xF2F2F2)) < 4.6:  # 4.5 plus a margin
            return False
    return True


def hue_of(h):
    L, a, b = oklab(h)
    return math.degrees(math.atan2(b, a)) % 360, L


def main():
    hues = [(25 + i * 360 / COLS) % 360 for i in range(COLS)]
    grid = [[None] * COLS for _ in ROWS_L]
    for r, L0 in enumerate(ROWS_L):
        for c, H in enumerate(hues):
            L = L0
            for _ in range(40):
                h = gamut(L, CHROMA[r], H)
                if text_ok(h) and de(h, LIME) >= LIME_MIN and de(h, 0x171717) >= 0.25:
                    break
                # Mid-greys fail both text colours: move away from the middle.
                if de(h, LIME) < LIME_MIN:
                    H = (H + 4) % 360
                L += 0.01 if L0 >= 0.62 else -0.01
            grid[r][c] = h
    # Legacy colours into their nearest cells (each cell at most once).
    taken = set()
    for lg in LEGACY:
        best = min(((de(lg, grid[r][c]), r, c) for r in range(len(ROWS_L)) for c in range(COLS) if (r, c) not in taken))
        _, r, c = best
        grid[r][c] = lg
        taken.add((r, c))
    print("// Generated by docs/polish/tools/make_palette.py (Cartwave's own palette; see the module docs).")
    print("pub const BASE: [[u32; 14]; 5] = [")
    for row in grid:
        print("    [" + ", ".join(f"0x{h:06X}" for h in row) + "],")
    print("];")
    print(f"/// The colours in use before the polish pass (each sits in its nearest cell above).")
    print("pub const LEGACY: [u32; 12] = [" + ", ".join(f"0x{h:06X}" for h in LEGACY) + "];")
    import sys
    flat = [h for row in grid for h in row]
    worst = min(max(contrast(c, 0x111111), contrast(c, 0xF2F2F2)) for h in flat for c in (h, lighten(h, 0.1)))
    near = sorted((de(h, LIME), f"{h:06X}") for h in flat)[:3]
    print(f"// min header contrast {worst:.2f}; nearest to lime: {near}", file=sys.stderr)


if __name__ == "__main__":
    main()
