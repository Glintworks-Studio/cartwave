"""Polish 2 §6.2: inventories every status message and dialog in crates/ui/src and
writes docs/polish2/notices.md.  usage: python notices.py"""
import glob
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SRC = os.path.join(REPO, "crates", "ui", "src")


def rel(f):
    return os.path.relpath(f, SRC).replace(os.sep, "/")


def main():
    rows, dialogs = [], []
    for f in sorted(glob.glob(os.path.join(SRC, "**", "*.rs"), recursive=True)):
        lines = open(f, encoding="utf-8").read().split("\n")
        for i, l in enumerate(lines):
            if re.search(r"set_status(_for)?\(", l) and "fn set_status" not in l:
                m = re.search(r'"([^"]*)"', l) or (re.search(r'"([^"]*)"', lines[i + 1]) if i + 1 < len(lines) else None)
                msg = m.group(1) if m else re.sub(r".*set_status(_for)?\(", "", l.strip())[:90]
                rows.append((rel(f), i + 1, msg))
            if re.search(r"MessageDialog|rfd::|ask_save|confirm_", l) and not l.strip().startswith("//"):
                dialogs.append((rel(f), i + 1, l.strip()[:110]))
    out = os.path.join(REPO, "docs", "polish2", "notices.md")
    with open(out, "w", encoding="utf-8", newline="\n") as o:
        o.write("# Polish 2 §6.2: every message, toast and notice\n\n")
        o.write("Generated by `docs/polish2/tools/notices.py` from `crates/ui/src`. **Before:** all of these showed in the "
                "floating notice capsule (bottom-right), with the audio problem text and the recovery offer. **Now:**\n\n")
        o.write("- every `set_status` message below is a **status-bar message** (left side, 8 s, then the idle text "
                "\"Saved · name\"), for example \"Saved\", the export report, autosave recovery, colour applied, an imported file;\n")
        o.write("- audio problems (no device, can't open, reconnecting) and dropouts are **persistent problems**: a warning "
                "icon on the status bar until they're resolved; a click lists them;\n")
        o.write("- \"Audio: now playing on …\" after a device change is a status-bar message;\n")
        o.write("- the **recovery offer** (RECOVER / DISCARD) stays in the capsule: it's a decision;\n")
        o.write("- native **dialogs** stay for decisions only (save prompts, the MIDI-drop conflict, profile changes, "
                "anything destructive): listed at the end.\n\n")
        o.write(f"## Status-bar messages ({len(rows)} call sites)\n\n| Where | Message (its first literal) |\n|---|---|\n")
        for f, l, m in rows:
            o.write(f"| `{f}:{l}` | {m.replace('|', '/')} |\n")
        o.write(f"\n## Dialogs: decisions, unchanged ({len(dialogs)} sites)\n\n| Where | Call |\n|---|---|\n")
        for f, l, m in dialogs:
            o.write(f"| `{f}:{l}` | `{m.replace('|', '/')}` |\n")
    print(out, len(rows), len(dialogs))


if __name__ == "__main__":
    main()
